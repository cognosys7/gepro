function comboIDE_FASE($nombre, $lstDatos, $valorInicial, $habil, $estilo) {
    ?>    
    <select data-trigger="hover" data-content="Seleccione la Fase" id="<?php echo $nombre; ?>" <?php if ($habil == 0) { ?>disabled="disabled"<?php } ?> class="required" name="<?php echo $nombre; ?>" <?php echo $estilo; ?> >
        <option value="">Seleccione una Opción</option>        
        <?php
        $lOption = "";
        for ($i = 0; $i < count($lstDatos); $i++) {
            if (strlen($lstDatos[$i]->IDE_FASE > 0)) {
                if ($lstDatos[$i]->IDE_FASE == $valorInicial) {
                    $lOption .= "<option value=\"" . $lstDatos[$i]->IDE_FASE . "\" selected=\"selected\">" . $lstDatos[$i]->DES_FASE . "</option>\n\r";
                } else {
                    $lOption .= "<option value=\"" . $lstDatos[$i]->IDE_FASE . "\">" . $lstDatos[$i]->DES_FASE . "</option>\n\r";
                }
            }
        }
        echo $lOption;
        ?>
    </select>
    <?php
}

